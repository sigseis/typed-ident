use crate::helpers::Boundaries;
use typed_ident::syntax::boundary::Options;

// =============================================================================
// TRAITS
// =============================================================================

// -----------------------------------------------------------------------------
pub trait OptionsExt: Options {
    fn boundaries() -> Boundaries {
        Boundaries {
            camel: Self::CAMEL,
            hat: Self::HAT,
            digit_to_lower: Self::DIGIT_TO_LOWER,
            digit_to_upper: Self::DIGIT_TO_UPPER,
            lower_to_digit: Self::LOWER_TO_DIGIT,
            upper_to_digit: Self::UPPER_TO_DIGIT,
        }
    }
}

// =============================================================================
// TRAIT IMPLS
// =============================================================================

// -----------------------------------------------------------------------------
impl<O: Options> OptionsExt for O {}
