use crate::Cli;
use crate::common::UnicodeVersion;
use anyhow::Result;

// =============================================================================
// COMMAND
// =============================================================================

// -----------------------------------------------------------------------------
pub fn list_versions(_cli: &Cli) -> Result<()> {
    for unicode in UnicodeVersion::list()? {
        println!("{}", unicode.version);
    }
    Ok(())
}
