use anyhow::Result;
use clap::Parser;
use cli::*;
use common::Command;

// =============================================================================
// MAIN
// =============================================================================

// -----------------------------------------------------------------------------
fn main() -> Result<()> {
    let cli = Cli::parse();
    match cli.command {
        Command::Generate => commands::generate(&cli),
        Command::ListVersions => commands::list_versions(&cli),
        Command::UpdateTables => commands::update_tables(&cli),
    }
}
