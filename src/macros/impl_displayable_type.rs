// =============================================================================
// MACROS
// =============================================================================

// -----------------------------------------------------------------------------
macro_rules! impl_displayable_type {
    (
        name=$name:ident,
        over=$over:ident,
        upper=$upper:literal,
        docs=$docs:expr,
    ) => {
        #[doc = $docs]
        #[repr(transparent)]
        pub struct $name<'a>($over<'a, $upper>);

        // ---------------------------------------------------------------------
        impl<'a> core::fmt::Display for $name<'a> {
            #[inline(always)]
            fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
                self.0.fmt(f)
            }
        }
    };
}

// =============================================================================
// EXPORTS
// =============================================================================

// -----------------------------------------------------------------------------
pub(crate) use impl_displayable_type;
