#[test]
fn expected_to_upper_camel_delimited() {
    // There was a bug mid-development where this transformed to TLS1__3Config
    assert_eq!(
        CamelIdent::new("TLS1_3Config")
            .unwrap()
            .to_upper_camel_delimited(),
        "Tls1_3Config"
    );
}
